/** 위경도에서 가장 가까운 대표 도시의 중기예보 코드 */
export function nearestMidRegion(lat, lon) {
  let best = null, bestD = Infinity;
  for (const [city, la, lo, taRegId, landRegId] of MID_CITIES) {
    // 짧은 거리 비교용 근사 (경도 간격은 위도에 따라 줄어든다)
    const d = (la - lat) ** 2 + ((lo - lon) * Math.cos((lat * Math.PI) / 180)) ** 2;
    if (d < bestD) { bestD = d; best = { city, taRegId, landRegId }; }
  }
  return best;
}

export function midRegionForGrid(nx, ny) {
  const { lat, lon } = gridToLatLon(nx, ny);
  return nearestMidRegion(lat, lon);
}
